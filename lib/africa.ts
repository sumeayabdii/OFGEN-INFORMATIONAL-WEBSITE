export const shapes = [mainland, madagascar];

export const bounds = { minLon: -18.5, maxLon: 52, minLat: -35.5, maxLat: 38 };

/** Equirectangular projection into a box of given width (height is derived). */
export function makeProjection(width: number) {
  const lonSpan = bounds.maxLon - bounds.minLon;
  const latSpan = bounds.maxLat - bounds.minLat;
  const k = width / lonSpan;
  const height = latSpan * k;
  return {
    width,
    height,
    project: ([lon, lat]: Pt): Pt => [(lon - bounds.minLon) * k, (bounds.maxLat - lat) * k],
  };
}

export function outlinePath(width: number) {
  const { project, height } = makeProjection(width);
  const d = shapes
    .map((s) => "M" + s.map((p) => project(p).map((n) => n.toFixed(1)).join(" ")).join("L") + "Z")
    .join("");
  return { d, height };
}
